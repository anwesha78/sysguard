# ── Main Monitor Loop ─────────────────────────────────
def run_monitor():
    log("=" * 55)
    log("SysGuard v1.0 — System Health Monitor STARTED")
    log(f"Thresholds → CPU:{CPU_THRESHOLD}% | RAM:{RAM_THRESHOLD}% | DISK:{DISK_THRESHOLD}%")
    log("=" * 55)

    consecutive_breach = {}   # metric -> count
    incident_log = []
    incident_active = False

    try:
        while True:
            metrics = collect_metrics()

            log(f"CPU: {metrics['cpu']}% | RAM: {metrics['ram']}% | "
                f"DISK: {metrics['disk']}% | "
                f"NET ↑{metrics['net_sent_mb']}MB ↓{metrics['net_recv_mb']}MB")

            anomalies = check_anomalies(metrics)

            if anomalies:
                for metric, value, threshold in anomalies:
                    consecutive_breach[metric] = consecutive_breach.get(metric, 0) + 1
                    log(f"⚠ WARNING — {metric} at {value}% "
                        f"(threshold: {threshold}%) "
                        f"[breach #{consecutive_breach[metric]}]", "WARN")

                    if consecutive_breach[metric] >= INCIDENT_COUNT:
                        if not incident_active:
                            log(f"🚨 INCIDENT DECLARED — {metric} breach sustained "
                                f"for {INCIDENT_COUNT} consecutive readings", "CRITICAL")
                            incident_active = True
                        incident_log.append({
                            "metric": metric,
                            "value": value,
                            "time": get_timestamp()
                        })
            else:
                # Reset breach counters when metrics normalise
                if incident_active and incident_log:
                    log("✅ Metrics normalised — generating RCA report...", "INFO")
                    rca_file = generate_rca(incident_log)
                    log(f"✅ RCA saved → {rca_file}", "INFO")
                    incident_log = []
                    incident_active = False
                consecutive_breach = {}

            time.sleep(CHECK_INTERVAL)

    except KeyboardInterrupt:
        log("SysGuard stopped by user.")
        if incident_log:
            log("Incident was active — generating final RCA before exit...", "WARN")
            generate_rca(incident_log)

if __name__ == "__main__":
    run_monitor()
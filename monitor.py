import psutil
import time
import os
from datetime import datetime

# ── Configuration ─────────────────────────────────────
CPU_THRESHOLD = 85        # % — alert if CPU exceeds this
RAM_THRESHOLD = 80        # % — alert if RAM exceeds this
DISK_THRESHOLD = 70       # % — alert if Disk exceeds this
CHECK_INTERVAL = 5        # seconds between each check
INCIDENT_COUNT = 3        # consecutive breaches = incident

LOG_DIR = "logs"
REPORT_DIR = "reports"

# ── Helpers ───────────────────────────────────────────
def get_timestamp():
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")

def get_log_filename():
    return os.path.join(LOG_DIR, f"sysguard_{datetime.now().strftime('%Y-%m-%d')}.log")

def log(message, level="INFO"):
    timestamp = get_timestamp()
    line = f"[{timestamp}] [{level}] {message}"
    print(line)
    with open(get_log_filename(), "a") as f:
        f.write(line + "\n")

# ── Metric Collection ─────────────────────────────────
def collect_metrics():
    cpu = psutil.cpu_percent(interval=1)
    ram = psutil.virtual_memory().percent
    disk = psutil.disk_usage('/').percent
    net = psutil.net_io_counters()
    net_sent_mb = round(net.bytes_sent / (1024 * 1024), 2)
    net_recv_mb = round(net.bytes_recv / (1024 * 1024), 2)
    return {
        "cpu": cpu,
        "ram": ram,
        "disk": disk,
        "net_sent_mb": net_sent_mb,
        "net_recv_mb": net_recv_mb,
        "timestamp": get_timestamp()
    }

# ── Anomaly Detection ─────────────────────────────────
def check_anomalies(metrics):
    anomalies = []
    if metrics["cpu"] > CPU_THRESHOLD:
        anomalies.append(("CPU", metrics["cpu"], CPU_THRESHOLD))
    if metrics["ram"] > RAM_THRESHOLD:
        anomalies.append(("RAM", metrics["ram"], RAM_THRESHOLD))
    if metrics["disk"] > DISK_THRESHOLD:
        anomalies.append(("DISK", metrics["disk"], DISK_THRESHOLD))
    return anomalies

